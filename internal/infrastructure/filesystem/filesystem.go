// Package filesystem implements the project-scoped file boundary.
package filesystem

import (
	"context"
	"crypto/sha256"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/Liapoldus/studio/internal/domain/interfaces"
	"github.com/Liapoldus/studio/internal/domain/models"
)

var (
	ErrPathOutsideProject = errors.New("path is outside the project")
	ErrSymlinkNotAllowed  = errors.New("project symlinks are not allowed")
)

type FileSystem struct{}

var _ interfaces.FileSystem = FileSystem{}

func (FileSystem) ReadFile(ctx context.Context, root, relative string) ([]byte, error) {
	if _, resolveErr := ResolvePath(root, relative); resolveErr != nil {
		return nil, resolveErr
	}
	if contextErr := ctx.Err(); contextErr != nil {
		return nil, contextErr
	}
	return fs.ReadFile(os.DirFS(filepath.Clean(root)), filepath.ToSlash(filepath.Clean(relative)))
}

func (FileSystem) WriteFile(ctx context.Context, root, relative string, data []byte) error {
	path, err := ResolvePath(root, relative)
	if err != nil {
		return err
	}
	if contextErr := ctx.Err(); contextErr != nil {
		return contextErr
	}
	if mkdirErr := os.MkdirAll(filepath.Dir(path), 0700); mkdirErr != nil {
		return mkdirErr
	}
	return writeAtomic(path, data)
}

// WriteFileIfDigest atomically replaces a Project file only when its current
// content still has expectedDigest. A per-file OS lock serializes independent
// Studio processes; the digest is checked again while holding that lock.
func (FileSystem) WriteFileIfDigest(ctx context.Context, root, relative, expectedDigest string, data []byte) (bool, error) {
	path, err := ResolvePath(root, relative)
	if err != nil {
		return false, err
	}
	if expectedDigest == "" {
		return false, nil
	}
	lockPath, err := settingsLockPath(root, relative)
	if err != nil {
		return false, err
	}
	if mkdirErr := os.MkdirAll(filepath.Dir(path), 0700); mkdirErr != nil { //nolint:gosec // path is resolved beneath the checked Project root.
		return false, mkdirErr
	}
	// lockPath is generated by settingsLockPath from the validated Project root and a fixed Studio-owned suffix.
	lock, err := os.OpenFile(lockPath, os.O_CREATE|os.O_RDWR, 0600) //nolint:gosec // lockPath is validated by settingsLockPath and cannot contain user path segments.
	if err != nil {
		return false, err
	}
	defer func() { discardError(lock.Close()) }()
	release, err := acquireFileLock(ctx, lock)
	if err != nil {
		return false, err
	}
	defer func() { discardError(release()) }()
	if contextErr := ctx.Err(); contextErr != nil {
		return false, contextErr
	}
	current, err := os.ReadFile(path) //nolint:gosec // path is confined and symlink-checked by ResolvePath.
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	digest := sha256.Sum256(current)
	if expectedDigest != fmt.Sprintf("sha256:%x", digest) {
		return false, nil
	}
	if err := writeAtomic(path, data); err != nil {
		return false, err
	}
	return true, nil
}

func writeAtomic(path string, data []byte) error {
	temporary, err := os.CreateTemp(filepath.Dir(path), ".studio-write-*")
	if err != nil {
		return err
	}
	temporaryPath := temporary.Name()
	defer func() { discardError(os.Remove(temporaryPath)) }() //nolint:gosec // temporaryPath is returned by CreateTemp in the resolved destination directory.
	if err := temporary.Chmod(0600); err != nil {
		discardError(temporary.Close())
		return err
	}
	if _, err := temporary.Write(data); err != nil {
		discardError(temporary.Close())
		return err
	}
	if err := temporary.Sync(); err != nil {
		discardError(temporary.Close())
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	return os.Rename(temporaryPath, path) //nolint:gosec // both paths are confined: one is CreateTemp output, the other ResolvePath output.
}

// CreateFile publishes a new file atomically without replacing an existing
// project file. The temporary file is placed beside the destination so the
// hard link is on the same filesystem.
func (FileSystem) CreateFile(ctx context.Context, root, relative string, data []byte) error {
	path, err := ResolvePath(root, relative)
	if err != nil {
		return err
	}
	if contextErr := ctx.Err(); contextErr != nil {
		return contextErr
	}
	if mkdirErr := os.MkdirAll(filepath.Dir(path), 0700); mkdirErr != nil {
		return mkdirErr
	}
	temporary, err := os.CreateTemp(filepath.Dir(path), ".studio-create-*")
	if err != nil {
		return err
	}
	temporaryPath := temporary.Name()
	defer func() { discardError(os.Remove(temporaryPath)) }()
	if err := temporary.Chmod(0600); err != nil {
		discardError(temporary.Close())
		return err
	}
	if _, err := temporary.Write(data); err != nil {
		discardError(temporary.Close())
		return err
	}
	if err := temporary.Sync(); err != nil {
		discardError(temporary.Close())
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	if err := os.Link(temporaryPath, path); err != nil {
		return err
	}
	return nil
}

func discardError(err error) { _ = err }

func ResolvePath(root, relative string) (string, error) {
	root = filepath.Clean(strings.TrimSpace(root))
	if !filepath.IsAbs(root) || strings.ContainsRune(root, '\x00') {
		return "", models.ErrInvalidProject
	}
	relative = filepath.Clean(strings.TrimSpace(relative))
	if relative == "." || filepath.IsAbs(relative) || strings.ContainsRune(relative, '\x00') {
		return "", ErrPathOutsideProject
	}
	parts := strings.Split(relative, string(filepath.Separator))
	if len(parts) > 0 && parts[0] == ".studio" {
		return "", ErrPathOutsideProject
	}
	joined := filepath.Join(root, relative)
	rel, err := filepath.Rel(root, joined)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", ErrPathOutsideProject
	}
	if err := rejectSymlinks(root, rel); err != nil {
		return "", err
	}
	return joined, nil
}

func rejectSymlinks(root, relative string) error {
	current := root
	for _, part := range strings.Split(relative, string(filepath.Separator)) {
		current = filepath.Join(current, part)
		info, err := os.Lstat(current) //nolint:gosec // current is built one segment at a time beneath the absolute Project root.
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil {
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return ErrSymlinkNotAllowed
		}
	}
	return nil
}
